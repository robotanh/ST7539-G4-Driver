/*
Stroke design (2px thick):
- vertical strokes: full height (0xFF)
- top bar: rows 0..1 => 0x03 in top byte
- bottom bar: rows 14..15 => 0xC0 in bottom byte
- middle bar (for H/E): rows 6..9  => top: 0xC0 (rows 6..7), bottom: 0x03 (rows 8..9)
*/

